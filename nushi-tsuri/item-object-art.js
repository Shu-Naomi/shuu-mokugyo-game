  function paint(draw) {
    const pixels = Array.from({ length: 32 }, () => Array(32).fill(null));
    const dot = (x, y, c) => { if (x >= 0 && x < 32 && y >= 0 && y < 32) pixels[y][x] = c; };
    const rect = (x, y, w, h, c) => {
      for (let yy = y; yy < y + h; yy++) for (let xx = x; xx < x + w; xx++) dot(xx, yy, c);
    };
    const line = (x, y, x2, y2, c) => {
      const dx = Math.abs(x2 - x), sx = x < x2 ? 1 : -1;
      const dy = -Math.abs(y2 - y), sy = y < y2 ? 1 : -1;
      let err = dx + dy;
      for (;;) {
        dot(x, y, c);
        if (x === x2 && y === y2) break;
        const e = err * 2;
        if (e >= dy) { err += dy; x += sx; }
        if (e <= dx) { err += dx; y += sy; }
      }
    };
    const poly = (points, c) => {
      for (let y = 0; y < 32; y++) for (let x = 0; x < 32; x++) {
        let inside = false;
        for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
          const [ax, ay] = points[i], [bx, by] = points[j];
          if ((ay > y + .5) !== (by > y + .5) && x + .5 < (bx - ax) * (y + .5 - ay) / (by - ay) + ax) inside = !inside;
        }
        if (inside) dot(x, y, c);
      }
    };
    const oval = (x, y, w, h, c) => {
      for (let yy = y; yy < y + h; yy++) for (let xx = x; xx < x + w; xx++) {
        if (((xx + .5 - x - w / 2) / (w / 2)) ** 2 + ((yy + .5 - y - h / 2) / (h / 2)) ** 2 <= 1) dot(xx, yy, c);
      }
    };
    const star = (x, y, c) => { rect(x + 2, y, 1, 5, c); rect(x, y + 2, 5, 1, c); };
    draw({ dot, rect, line, poly, oval, star });
    const colors = new Map();
    for (let y = 0; y < 32; y++) for (let x = 0; x < 32;) {
      const color = pixels[y][x];
      if (!color) { x++; continue; }
      let end = x + 1;
      while (end < 32 && pixels[y][end] === color) end++;
      colors.set(color, (colors.get(color) || "") + `M${x} ${y}h${end - x}v1h-${end - x}z`);
      x = end;
    }
    return `<svg xmlns="http://www.w3.org/2000/svg" class="pixel-item-icon item-object-pixel-icon" width="32" height="32" viewBox="0 0 32 32" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${Array.from(colors, ([fill, d]) => `<path fill="${fill}" d="${d}"/>`).join("")}</svg>`;
  }
